/**
 * Emoji for words as people type them in chats, mostly Brazilian
 * Portuguese. The Unicode keywords know "pizza" and "gato" but rank
 * oddly for everyday chat ("bom" -> 🦸, "fome" -> 🍍) and miss slang
 * ("vlw", "tmj", "kkkk"), so these come first. Keys are lowercase and
 * without accents, as [EmojiData.normalize] leaves a word.
