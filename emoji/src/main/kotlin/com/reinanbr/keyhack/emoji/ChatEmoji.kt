internal object ChatEmoji {
    /** The emoji for [key], best first; empty when the list has none. */
    fun forKey(key: String): List<String> = WORDS[key]?.split(' ').orEmpty()

    /** Laughs and other stretched spellings collapse to one key: "kkkkk" -> "kkk", "hahaha" -> "haha". */
    fun key(word: String): String = LAUGHS.firstOrNull { (re, _) -> re.matches(word) }?.second ?: word

    /**
     * Common words whose Unicode keywords give nonsense ("de" -> 🏃, "isso"
     * -> 🫹, "no" -> 🚭): no emoji unless the chat list has some.
     */
    val NONE =
        setOf(
            "de", "do", "da", "dos", "das", "no", "na", "nos", "nas", "em", "um", "uma", "se", "me", "te", "eu", "voce",
